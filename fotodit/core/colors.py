"""ICC color profile analysis and conversion of pixels to sRGB.

A color profile is metadata too (it can contain a description, copyright, device maker/model and a
creation date) and is stripped. But if the profile is not sRGB (e.g. Display P3 in iPhone photos,
Adobe RGB, CMYK), just removing it distorts the colors, because an image without a profile is assumed
to be sRGB everywhere. Therefore:

* If the profile is equivalent to sRGB → it is removed and the pixels stay unchanged.
* Otherwise → the pixels are first converted to sRGB with LittleCMS, then the profile is removed.

Whether a profile is "equivalent to sRGB" is decided by measuring, not by its name: a grid of
729 colors is converted to sRGB through the profile and its deviation from the identity transform
is measured (at most 2 levels at 8 bits).

With "Geniş renk alanını koru" (keep the wide color space) the pixels are not converted: if the
profile is equivalent to Display P3, Adobe RGB (1998) or ProPhoto RGB (measured the same way), a
clean standard profile generated by `iccgen` is embedded instead of the original one, so no device
name, copyright text or date travels along. Other profiles are converted to sRGB as before.
"""

from __future__ import annotations

import functools
import hashlib
import io
import threading
from dataclasses import dataclass

from PIL import Image, ImageChops, ImageCms, ImageStat

from ..i18n import t
from . import iccgen

_SRGB = ImageCms.createProfile("sRGB")
_INTENT = ImageCms.Intent.PERCEPTUAL
_FLAGS = ImageCms.Flags.BLACKPOINTCOMPENSATION

_lock = threading.Lock()
_cache: dict[bytes, "IccInfo"] = {}


@dataclass(frozen=True)
class IccInfo:
    valid: bool
    colorspace: str = ""
    description: str = ""
    srgb_equivalent: bool = False


def _rgb_grid() -> Image.Image:
    levels = (0, 32, 64, 96, 128, 160, 192, 224, 255)
    im = Image.new("RGB", (81, 9))
    px = im.load()
    for r, rv in enumerate(levels):
        for g, gv in enumerate(levels):
            for b, bv in enumerate(levels):
                px[r * 9 + g, b] = (rv, gv, bv)
    return im


_GRID = _rgb_grid()
_GRAY_RAMP = Image.linear_gradient("L").resize((256, 1))


def _profile(icc: bytes) -> ImageCms.ImageCmsProfile:
    return ImageCms.ImageCmsProfile(io.BytesIO(icc))


def _max_and_mean(a: Image.Image, b: Image.Image) -> tuple[int, float]:
    diff = ImageChops.difference(a, b)
    extrema = diff.getextrema()
    if isinstance(extrema[0], tuple):
        mx = max(e[1] for e in extrema)
    else:
        mx = extrema[1]
    mean = sum(ImageStat.Stat(diff).mean) / len(diff.getbands())
    return mx, mean


def analyze_icc(icc: bytes) -> IccInfo:
    key = hashlib.sha1(icc).digest()
    with _lock:
        cached = _cache.get(key)
    if cached:
        return cached
    info = _analyze(icc)
    with _lock:
        _cache[key] = info
    return info


def _analyze(icc: bytes) -> IccInfo:
    try:
        prof = _profile(icc)
        cs = prof.profile.xcolor_space.strip().upper()
        desc = (ImageCms.getProfileDescription(prof) or "").strip()
    except (ImageCms.PyCMSError, OSError, ValueError, TypeError):
        return IccInfo(valid=False)
    equivalent = False
    try:
        if cs == "RGB":
            out = ImageCms.profileToProfile(
                _GRID, prof, _SRGB, renderingIntent=ImageCms.Intent.RELATIVE_COLORIMETRIC, outputMode="RGB"
            )
            mx, mean = _max_and_mean(out, _GRID)
            equivalent = mx <= 2 and mean <= 0.25
        elif cs == "GRAY":
            out = ImageCms.profileToProfile(
                _GRAY_RAMP, prof, _SRGB, renderingIntent=ImageCms.Intent.RELATIVE_COLORIMETRIC, outputMode="RGB"
            )
            mx, mean = _max_and_mean(out, _GRAY_RAMP.convert("RGB"))
            equivalent = mx <= 2 and mean <= 0.25
    except (ImageCms.PyCMSError, OSError, ValueError):
        return IccInfo(valid=False, colorspace=cs, description=desc)
    return IccInfo(True, cs, desc, equivalent)


def icc_description(icc: bytes) -> str | None:
    info = analyze_icc(icc)
    return info.description or (info.colorspace or None)


def needs_conversion(icc: bytes | None, mode: str) -> bool:
    """Do the pixels need converting before the profile is removed?

    Without a profile there is nothing to remove and the appearance does not change (except LAB:
    LAB pixels always have to be converted to sRGB).
    """
    if not icc:
        return mode == "LAB"
    info = analyze_icc(icc)
    if not info.valid:
        return False
    if mode == "CMYK":
        return info.colorspace == "CMYK"
    if info.colorspace == "RGB" and mode in ("RGB", "RGBA", "P", "PA"):
        return not info.srgb_equivalent
    if info.colorspace == "GRAY" and mode in ("L", "LA", "1", "I;16", "I"):
        return not info.srgb_equivalent
    return False


def profile_matches(icc: bytes | None, mode: str) -> bool:
    """Does the profile fit this pixel mode (can it be carried over as is when converting with the
    metadata kept)?"""
    if not icc:
        return False
    info = analyze_icc(icc)
    if not info.valid:
        return False
    return (info.colorspace == "RGB" and mode == "RGB") or (info.colorspace == "GRAY" and mode == "L")


def to_srgb(im: Image.Image, icc: bytes | None) -> tuple[Image.Image, str | None]:
    """Converts the image to sRGB (or to sRGB gray if it is grayscale).

    Returns (image, warning). The image mode becomes RGB/RGBA/L/LA.
    """
    mode = im.mode
    if not icc:
        if mode == "CMYK":
            return im.convert("RGB"), None
        if mode == "LAB":
            return _lab_to_rgb(im), None
        return im, None
    info = analyze_icc(icc)
    if not info.valid:
        warning = t("colors.unreadable")
        return (im.convert("RGB") if mode == "CMYK" else im), warning
    cs = info.colorspace
    try:
        if cs == "RGB" and mode in ("RGB", "RGBA"):
            if info.srgb_equivalent:
                return im, None
            return _transform(im, icc, mode), None
        if cs == "GRAY" and mode in ("L", "LA"):
            if info.srgb_equivalent:
                return im, None
            alpha = im.getchannel("A") if mode == "LA" else None
            base = im.getchannel("L") if mode == "LA" else im
            gray = _transform(base, icc, "RGB").convert("L")
            return (Image.merge("LA", (gray, alpha)) if alpha else gray), None
        if cs == "CMYK" and mode == "CMYK":
            return _transform(im, icc, "RGB"), None
        if cs == "LAB" and mode == "LAB":
            return _lab_to_rgb(im), None
    except (ImageCms.PyCMSError, OSError, ValueError) as exc:
        warning = t("colors.failed", error=exc)
        return (im.convert("RGB") if mode == "CMYK" else im), warning
    warning = t("colors.mismatch")
    if mode == "CMYK":
        return im.convert("RGB"), warning
    if mode == "LAB":
        return _lab_to_rgb(im), warning
    return im, warning


def _transform(im: Image.Image, icc: bytes, out_mode: str) -> Image.Image:
    return ImageCms.profileToProfile(
        im, _profile(icc), _SRGB, renderingIntent=_INTENT, outputMode=out_mode, flags=_FLAGS
    )


def _lab_to_rgb(im: Image.Image) -> Image.Image:
    lab = ImageCms.createProfile("LAB")
    return ImageCms.profileToProfile(im, lab, _SRGB, outputMode="RGB")


# ------------------------------------------------------------ keeping wide color spaces


@dataclass(frozen=True)
class StandardProfile:
    name: str  # for the UI
    icc: bytes  # the clean profile that is embedded


@functools.lru_cache(maxsize=1)
def _standards() -> tuple[StandardProfile, ...]:
    return (
        StandardProfile("Display P3", iccgen.rgb_profile("Display P3", iccgen.PRIMARIES[12], "srgb")),
        StandardProfile("Adobe RGB", iccgen.adobe_rgb_profile()),
        StandardProfile("ProPhoto RGB", iccgen.rgb_profile("ProPhoto RGB", iccgen.PROPHOTO_RGB, 1.8)),
    )


_standard_cache: dict[bytes, StandardProfile | None] = {}


def standard_profile(icc: bytes | None) -> StandardProfile | None:
    """The standard wide color space the RGB profile describes (with a clean profile to embed
    instead), or None (sRGB, gray, CMYK, an unknown or broken profile)."""
    if not icc:
        return None
    key = hashlib.sha1(icc).digest()
    with _lock:
        if key in _standard_cache:
            return _standard_cache[key]
    found = None
    info = analyze_icc(icc)
    if info.valid and info.colorspace == "RGB" and not info.srgb_equivalent:
        try:
            source = _profile(icc)
            for candidate in _standards():
                if icc == candidate.icc:
                    found = candidate
                    break
                out = ImageCms.profileToProfile(_GRID, source, _profile(candidate.icc),
                                                renderingIntent=ImageCms.Intent.RELATIVE_COLORIMETRIC, outputMode="RGB")
                mx, mean = _max_and_mean(out, _GRID)
                if mx <= 2 and mean <= 0.25:
                    found = candidate
                    break
        except (ImageCms.PyCMSError, OSError, ValueError):
            found = None
    with _lock:
        _standard_cache[key] = found
    return found


def is_clean_profile(icc: bytes | None) -> bool:
    """Is this one of the clean standard profiles Fotodit embeds?"""
    return bool(icc) and any(icc == s.icc for s in _standards())
